              var saved = null;
              try { saved = localStorage.getItem('theme'); } catch (e) {}
              if (saved) document.documentElement.setAttribute('data-theme', saved);

              var label = function () {
                var dark = document.documentElement.getAttribute('data-theme') === 'dark';
                button.textContent = dark ? '☀' : '☾';
                button.setAttribute('aria-label', dark ? 'Switch to light mode' : 'Switch to dark mode');
              };
              label();

              button.addEventListener('click', function () {
                var dark = document.documentElement.getAttribute('data-theme') === 'dark';
                var next = dark ? 'light' : 'dark';
                document.documentElement.setAttribute('data-theme', next);
                try { localStorage.setItem('theme', next); } catch (e) {}
                label();
              });
            })();
            JS;
        }

        if ($has('cookie')) {
            $js .= <<<'JS'


            /* Cookie notice — dismissed choice is remembered. */
            (function () {
              'use strict';
              var bar = document.querySelector('.cookie');
              if (!bar) return;

              var seen = null;
              try { seen = localStorage.getItem('cookie-notice'); } catch (e) {}
              if (seen) { bar.hidden = true; return; }

              bar.hidden = false;
              Array.prototype.forEach.call(bar.querySelectorAll('button'), function (button) {
                button.addEventListener('click', function () {
                  bar.hidden = true;
                  try { localStorage.setItem('cookie-notice', 'done'); } catch (e) {}
                });
              });
            })();
            JS;
        }

        return $js;
    }
